-- 3. QUERIES

-- 1. All users
SELECT * FROM USERS;

-- 2. All languages with version and limits
SELECT LANGUAGE_NAME, VERSION, TIME_MULTIPLIER, MEMORY_LIMIT_MB FROM LANGUAGES;

-- 3. All problems with the author's username, easiest first
SELECT P.TITLE, P.DIFFICULTY, P.POINTS, U.USERNAME AS AUTHOR
FROM PROBLEMS P
JOIN USERS U ON P.AUTHOR_ID = U.USER_ID
ORDER BY P.POINTS, P.TITLE;

-- 4. Tags of problem 3
SELECT T.TAG_NAME
FROM PROBLEM_TAGS PT
JOIN TAGS T ON PT.TAG_ID = T.TAG_ID
WHERE PT.PROBLEM_ID = 3;

-- 5. Submissions of user 2, ordered by submit time
SELECT * FROM SUBMISSIONS
WHERE USER_ID = 2
ORDER BY SUBMIT_TIME;

-- 6. Number of submissions for each problem
SELECT P.TITLE, COUNT(S.SUBMISSION_ID) AS SUBMISSION_COUNT
FROM PROBLEMS P
LEFT JOIN SUBMISSIONS S ON P.PROBLEM_ID = S.PROBLEM_ID
GROUP BY P.TITLE;

-- 7. Accepted submissions with username, problem title and language
SELECT S.SUBMISSION_ID, U.USERNAME, P.TITLE, L.LANGUAGE_NAME
FROM SUBMISSIONS S
JOIN USERS U ON S.USER_ID = U.USER_ID
JOIN PROBLEMS P ON S.PROBLEM_ID = P.PROBLEM_ID
JOIN LANGUAGES L ON S.LANGUAGE_ID = L.LANGUAGE_ID
WHERE S.STATUS = 'ACCEPTED';

-- 8. Hard problems
SELECT * FROM PROBLEMS
WHERE DIFFICULTY = 'HARD';

-- 9. Effective time limit of each submission in milliseconds
SELECT S.SUBMISSION_ID, P.TITLE, L.LANGUAGE_NAME,
       P.TIME_LIMIT_MS * L.TIME_MULTIPLIER AS EFFECTIVE_LIMIT_MS
FROM SUBMISSIONS S
JOIN PROBLEMS P ON S.PROBLEM_ID = P.PROBLEM_ID
JOIN LANGUAGES L ON S.LANGUAGE_ID = L.LANGUAGE_ID;

-- 10. Leaderboard: solved problems and total points for each user
SELECT U.USERNAME,
       COUNT(SOLVED.PROBLEM_ID) AS SOLVED_PROBLEMS,
       NVL(SUM(P.POINTS), 0) AS TOTAL_POINTS
FROM USERS U
LEFT JOIN (SELECT DISTINCT USER_ID, PROBLEM_ID
           FROM SUBMISSIONS
           WHERE STATUS = 'ACCEPTED') SOLVED ON U.USER_ID = SOLVED.USER_ID
LEFT JOIN PROBLEMS P ON SOLVED.PROBLEM_ID = P.PROBLEM_ID
GROUP BY U.USERNAME
ORDER BY TOTAL_POINTS DESC, U.USERNAME;

-- 11. Submissions, accepted submissions and acceptance rate for each problem
SELECT P.TITLE,
       COUNT(S.SUBMISSION_ID) AS TOTAL_SUBMISSIONS,
       COUNT(CASE WHEN S.STATUS = 'ACCEPTED' THEN 1 END) AS ACCEPTED,
       NVL(ROUND(COUNT(CASE WHEN S.STATUS = 'ACCEPTED' THEN 1 END) * 100 / NULLIF(COUNT(S.SUBMISSION_ID), 0), 1), 0) AS ACCEPTANCE_RATE
FROM PROBLEMS P
LEFT JOIN SUBMISSIONS S ON P.PROBLEM_ID = S.PROBLEM_ID
GROUP BY P.TITLE;

-- 12. Passed tests, total tests, average runtime and peak memory for each judged submission
SELECT S.SUBMISSION_ID, U.USERNAME, P.TITLE, S.STATUS,
       COUNT(CASE WHEN T.VERDICT = 'PASS' THEN 1 END) AS PASSED_TESTS,
       COUNT(T.RESULT_ID) AS TOTAL_TESTS,
       ROUND(AVG(T.RUNTIME_MS), 1) AS AVG_RUNTIME_MS,
       MAX(T.MEMORY_KB) AS PEAK_MEMORY_KB
FROM SUBMISSIONS S
JOIN USERS U ON S.USER_ID = U.USER_ID
JOIN PROBLEMS P ON S.PROBLEM_ID = P.PROBLEM_ID
LEFT JOIN TEST_RESULTS T ON S.SUBMISSION_ID = T.SUBMISSION_ID
WHERE S.STATUS <> 'PENDING'
GROUP BY S.SUBMISSION_ID, U.USERNAME, P.TITLE, S.STATUS
ORDER BY S.SUBMISSION_ID;

-- 13. Judging time of each judged submission in seconds, longest first
SELECT SUBMISSION_ID, (JUDGE_TIME - SUBMIT_TIME) * 24 * 60 * 60 AS JUDGING_SECONDS
FROM SUBMISSIONS
WHERE JUDGE_TIME IS NOT NULL
ORDER BY JUDGING_SECONDS DESC;

-- 14. Problems that nobody has attempted
SELECT P.TITLE
FROM PROBLEMS P
LEFT JOIN SUBMISSIONS S ON P.PROBLEM_ID = S.PROBLEM_ID
WHERE S.SUBMISSION_ID IS NULL;

-- 15. Tests marked PASS that ran longer than the effective time limit (should return nothing)
SELECT T.RESULT_ID
FROM TEST_RESULTS T
JOIN SUBMISSIONS S ON T.SUBMISSION_ID = S.SUBMISSION_ID
JOIN PROBLEMS P ON S.PROBLEM_ID = P.PROBLEM_ID
JOIN LANGUAGES L ON S.LANGUAGE_ID = L.LANGUAGE_ID
WHERE T.VERDICT = 'PASS'
  AND T.RUNTIME_MS > P.TIME_LIMIT_MS * L.TIME_MULTIPLIER;
