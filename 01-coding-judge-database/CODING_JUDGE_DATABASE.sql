-- CODING JUDGE PLATFORM DATABASE (Oracle SQL)

-- 1. TABLES

CREATE TABLE USERS(
    USER_ID NUMBER PRIMARY KEY,
    USERNAME VARCHAR2(30) NOT NULL UNIQUE,
    FIRST_NAME VARCHAR2(30),
    LAST_NAME VARCHAR2(30),
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    REGISTRATION_DATE DATE
);

CREATE TABLE LANGUAGES(
    LANGUAGE_ID NUMBER PRIMARY KEY,
    LANGUAGE_NAME VARCHAR2(30) NOT NULL UNIQUE,
    VERSION VARCHAR2(20) NOT NULL,
    TIME_MULTIPLIER NUMBER CHECK (TIME_MULTIPLIER > 0),
    MEMORY_LIMIT_MB NUMBER CHECK (MEMORY_LIMIT_MB > 0)
);

CREATE TABLE PROBLEMS(
    PROBLEM_ID NUMBER PRIMARY KEY,
    AUTHOR_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    TITLE VARCHAR2(100) NOT NULL UNIQUE,
    DIFFICULTY VARCHAR2(10) CHECK (DIFFICULTY IN ('EASY','MEDIUM','HARD')),
    TIME_LIMIT_MS NUMBER CHECK (TIME_LIMIT_MS > 0),
    POINTS NUMBER CHECK (POINTS > 0),
    CREATED_DATE DATE
);

CREATE TABLE TAGS(
    TAG_ID NUMBER PRIMARY KEY,
    TAG_NAME VARCHAR2(30) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255)
);

CREATE TABLE PROBLEM_TAGS(
    PROBLEM_ID NUMBER REFERENCES PROBLEMS(PROBLEM_ID),
    TAG_ID NUMBER REFERENCES TAGS(TAG_ID),
    PRIMARY KEY (PROBLEM_ID, TAG_ID)
);

CREATE TABLE SUBMISSIONS(
    SUBMISSION_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    PROBLEM_ID NUMBER NOT NULL REFERENCES PROBLEMS(PROBLEM_ID),
    LANGUAGE_ID NUMBER NOT NULL REFERENCES LANGUAGES(LANGUAGE_ID),
    SUBMIT_TIME DATE NOT NULL,
    JUDGE_TIME DATE,
    STATUS VARCHAR2(20) CHECK (STATUS IN ('PENDING','ACCEPTED','WRONG_ANSWER','TIME_LIMIT','RUNTIME_ERROR','COMPILE_ERROR')),
    CODE_LENGTH NUMBER CHECK (CODE_LENGTH >= 0),
    CHECK (JUDGE_TIME >= SUBMIT_TIME),
    CHECK ((STATUS = 'PENDING' AND JUDGE_TIME IS NULL) OR (STATUS <> 'PENDING' AND JUDGE_TIME IS NOT NULL))
);

CREATE TABLE TEST_RESULTS(
    RESULT_ID NUMBER PRIMARY KEY,
    SUBMISSION_ID NUMBER NOT NULL REFERENCES SUBMISSIONS(SUBMISSION_ID),
    TEST_NUMBER NUMBER NOT NULL CHECK (TEST_NUMBER > 0),
    RUNTIME_MS NUMBER CHECK (RUNTIME_MS >= 0),
    MEMORY_KB NUMBER CHECK (MEMORY_KB >= 0),
    VERDICT VARCHAR2(10) CHECK (VERDICT IN ('PASS','FAIL','TIMEOUT','CRASH')),
    UNIQUE (SUBMISSION_ID, TEST_NUMBER)
);


